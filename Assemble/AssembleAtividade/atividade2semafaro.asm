ORG 0000H

INICIO:

    CLR P1.0
    SETB P1.1
    SETB P1.2
    ACALL DELAY_LONGO

    SETB P1.0
    CLR P1.1
    ACALL DELAY_CURTO

    SETB P1.1
    CLR P1.2
    ACALL DELAY_LONGO

    SJMP INICIO

DELAY_CURTO:
    MOV R1, #50
    SJMP DELAY

DELAY_LONGO:
    MOV R1, #200

DELAY:
LOOP1:  MOV R2, #255
LOOP2:  MOV R3, #255
LOOP3:  DJNZ R3, LOOP3
        DJNZ R2, LOOP2
        DJNZ R1, LOOP1
        RET

END